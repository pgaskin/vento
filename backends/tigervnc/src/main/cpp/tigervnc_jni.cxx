// ---- the protocol thread -------------------------------------------------

void Session::runCmd(Conn *conn, Cmd &cmd) {
    switch (cmd.type) {
        case CMD_POINTER:
            if (!viewOnly_) {
                // Bits 0–8: the seam's mask is RFB's, and TigerVNC carries the
                // eighth and ninth through the extended pointer message when
                // the server has asked for it.
                conn->writer()->writePointerEvent(core::Point(cmd.a, cmd.b),
                                                  (uint16_t) (cmd.c & 0x1FF));
            }
            break;
        case CMD_KEY_DOWN:
            if (!viewOnly_) {
                // The key's identity is the seam's `keyId`, which is exactly
                // what TigerVNC's `systemKeyCode` is for: it keeps the map of
                // held keys itself and releases the keysym recorded at press
                // time. The other two clients need that map in the shim.
                conn->sendKeyPress(cmd.b, 0, (uint32_t) cmd.a);
            }
            break;
        case CMD_KEY_UP:
            if (!viewOnly_) {
                conn->sendKeyRelease(cmd.a);
            }
            break;
        case CMD_RELEASE_KEYS:
            if (!viewOnly_) {
                conn->releaseAllKeys();
            }
            break;
        case CMD_CLIPBOARD:
            // The extended clipboard is an announcement and a request, not a
            // send: the server asks for the text if it wants it, which is when
            // `pendingClipboard` is read.
            clipboardOut_ = cmd.text;
            if (!viewOnly_) {
                conn->announceClipboard(true);
            }
            break;
        case CMD_PICTURE:
            applyPicture(conn);
            break;
        case CMD_RESIZE: {
            // Guarded rather than attempted: writeSetDesktopSize throws where
            // the server never offered one, and an exception out of here ends
            // the session.
            if (viewOnly_ || !conn->server.supportsSetDesktopSize
                    || (conn->server.width() == cmd.a && conn->server.height() == cmd.b)) {
                break;
            }
            // One screen covering the desktop, which is the FLTK viewer's
            // windowed case and the only one a phone has. The screen kept is
            // the server's own, so its id and flags go back as they came: a
            // server matches what it is sent against the screens it has.
            rfb::ScreenSet layout = conn->server.screenLayout();
            while (layout.num_screens() > 1) {
                rfb::ScreenSet::iterator second = layout.begin();
                ++second;
                layout.remove_screen(second->id);
            }
            if (layout.num_screens() == 0) {
                layout.add_screen(rfb::Screen());
            }
            layout.begin()->dimensions.tl.x = 0;
            layout.begin()->dimensions.tl.y = 0;
            layout.begin()->dimensions.br.x = cmd.a;
            layout.begin()->dimensions.br.y = cmd.b;
            if (!layout.validate(cmd.a, cmd.b)) {
                LOGW("not asking for %dx%d: the layout it would need is not valid", cmd.a, cmd.b);
                break;
            }
            conn->writer()->writeSetDesktopSize(cmd.a, cmd.b, layout);
            break;
        }
        case CMD_DISCONNECT: {
            const std::lock_guard<std::mutex> guard(lock_);
            quit_ = true;
            break;
        }
    }
}

// `host::port` is the one unbracketed address with two colons in it that is not
// an IPv6 literal somebody left the brackets off.
static bool bareLiteral(const std::string &address) {
    const size_t first = address.find(':');
    const size_t last = address.rfind(':');
    if (first == std::string::npos || first == last) {
        return false;
    }
    return !(last == first + 1 && address.find(':', last + 1) == std::string::npos);
}

// An address is `host`, `host:port`, `[literal]` or `[literal]:port`. A bare
// IPv6 literal is refused in words rather than guessed at, because `:1` is a
// display number here and `::1:1` cannot be an address and a display at once —
// what the guess used to produce was `::`, which is the wildcard address. The
// split itself is upstream's: it has the display rule, the `host::port` escape
// from it, and unit tests, none of which is worth writing again beside it.
static bool splitAddress(const std::string &address, std::string *host, int *port,
                         std::string *why) {
    const size_t from = address.find_first_not_of(" \t");
    const size_t to = address.find_last_not_of(" \t");
    const std::string trimmed =
            from == std::string::npos ? "" : address.substr(from, to - from + 1);
    if (trimmed.empty() || trimmed[0] == ':') {
        *why = "No host in address";
        return false;
    }
    if (trimmed[0] != '[' && bareLiteral(trimmed)) {
        *why = "IPv6 addresses must be bracketed, like [::1]:5900, not " + trimmed;
        return false;
    }
    try {
        network::getHostAndPort(trimmed.c_str(), host, port, 5900);
    } catch (const std::exception &e) {
        *why = std::string("Not an address: ") + e.what();
        return false;
    }
    return true;
}

int Session::openSocket(std::string *why) {
    std::string host;
    int port = 5900;
    if (!splitAddress(address_, &host, &port, why)) {
        return -1;
    }

    char service[16];
    snprintf(service, sizeof(service), "%d", port);
    struct addrinfo hints = {};
    hints.ai_family = AF_UNSPEC;
    hints.ai_socktype = SOCK_STREAM;
    struct addrinfo *ai = nullptr;
    const int gai = getaddrinfo(host.c_str(), service, &hints, &ai);
    if (gai != 0) {
        *why = std::string("Cannot find ") + host + ": " + gai_strerror(gai);
        return -1;
    }

    int fd = -1;
    bool cancelled = false;
    *why = "Could not connect";
    for (struct addrinfo *a = ai; a != nullptr && fd < 0 && !cancelled; a = a->ai_next) {
        const int candidate = socket(a->ai_family, SOCK_STREAM | SOCK_NONBLOCK, 0);
        if (candidate < 0) {
            continue;
        }
        if (connect(candidate, a->ai_addr, a->ai_addrlen) == 0) {
            fd = candidate;
            break;
        }
        if (errno != EINPROGRESS) {
            *why = std::string("Could not connect: ") + strerror(errno);
            close(candidate);
            continue;
        }
        struct pollfd fds[2] = {{candidate, POLLOUT, 0}, {wake_[0], POLLIN, 0}};
        const auto deadline = std::chrono::steady_clock::now()
                + std::chrono::milliseconds(connectTimeoutMs_);
        int err = ETIMEDOUT;
        // The doorbell is in this poll so that a disconnect while the socket is
        // still opening does not have to wait out the deadline. But the app
        // rings it for every command it queues, and one queued during the
        // connect — a focus change, the options the session screen sets on the
        // way in — is not a cancellation: it has to be drained and waited past,
        // or the very first connection of a session reports a server that never
        // answered while the second one works.
        for (;;) {
            int remaining = -1;
            if (connectTimeoutMs_ > 0) {
                remaining = (int) std::chrono::duration_cast<std::chrono::milliseconds>(
                        deadline - std::chrono::steady_clock::now()).count();
                remaining = remaining < 0 ? 0 : remaining;
            }
            fds[0].revents = fds[1].revents = 0;
            const int r = poll(fds, 2, remaining);
            if (r < 0) {
                if (errno == EINTR) {
                    continue;
                }
                err = errno;
                break;
            }
            if (r == 0) {
                err = ETIMEDOUT;
                break;
            }
            if ((fds[1].revents & POLLIN) != 0) {
                char buf[64];
                while (read(wake_[0], buf, sizeof(buf)) > 0) {
                    // the doorbell, and nothing in it
                }
                const std::lock_guard<std::mutex> guard(lock_);
                if (quit_) {
                    cancelled = true;
                    break;
                }
            }
            if ((fds[0].revents & (POLLOUT | POLLERR | POLLHUP)) != 0) {
                socklen_t len = sizeof(err);
                if (getsockopt(candidate, SOL_SOCKET, SO_ERROR, &err, &len) != 0) {
                    err = errno;
                }
                break;
            }
        }
        if (!cancelled && err == 0) {
            fd = candidate;
            break;
        }
        // An empty reason is what the caller reads as "somebody asked for this".
        *why = cancelled ? ""
                : err == ETIMEDOUT ? "The server did not answer"
                : std::string("Could not connect: ") + strerror(err);
        close(candidate);
    }
    freeaddrinfo(ai);

    if (fd >= 0) {
        fcntl(fd, F_SETFL, fcntl(fd, F_GETFL, 0) & ~O_NONBLOCK);
        serverHost_ = host;
        serverPort_ = port;
    }
    return fd;
}

void Session::run() {
    JNIEnv *env = nullptr;
    vm_->AttachCurrentThread(&env, nullptr);

    std::string why;
    const int fd = openSocket(&why);
    if (fd < 0) {
        closed(why);
        vm_->DetachCurrentThread();
        return;
    }

    fd_.store(fd);
    std::unique_ptr<network::TcpSocket> sock;
    std::unique_ptr<Conn> conn;
    std::string detail;
    try {
        sock.reset(new network::TcpSocket(fd));
        installSecurityTypes();
        conn.reset(new Conn(this));
        conn->setShared(shared_);
        // Nothing is negotiated yet, so this is only the state the connection
        // starts in; the pixel format it decides is asked for in initDone.
        applyPicture(conn.get());
        conn->setServerName(serverHost_.c_str());
        conn->setStreams(&sock->inStream(), &sock->outStream());
        conn->initialiseProtocol();

        for (;;) {
            bool paused;
            std::deque<Cmd> pending;
            {
                std::unique_lock<std::mutex> guard(lock_);
                if (quit_) {
                    break;
                }
                paused = paused_;
                // Held rather than dropped until the connection is up: every
                // command below needs a writer, and there is none until the
                // handshake finishes — which can take as long as somebody
                // takes to answer a question about a certificate.
                if (connected_) {
                    pending.swap(queue_);
                }
            }
            for (Cmd &cmd : pending) {
                runCmd(conn.get(), cmd);
            }
            {
                const std::lock_guard<std::mutex> guard(lock_);
                if (quit_) {
                    break;
                }
            }

            sock->outStream().flush();
            setTraffic((jlong) conn->getInStream()->pos(),
                       (jlong) conn->getOutStream()->length());

            // Anything already in the buffer is a message nobody is going to
            // be told about by poll().
            bool buffered = !paused && sock->inStream().hasData(1);
            if (!buffered) {
                struct pollfd fds[2];
                int n = 0;
                fds[n++] = {wake_[0], POLLIN, 0};
                if (!paused) {
                    fds[n++] = {sock->getFd(), POLLIN, 0};
                }
                const int timeout = core::Timer::checkTimeouts();
                const int r = poll(fds, n, timeout > 0 ? timeout : -1);
                if (r < 0 && errno != EINTR) {
                    break;
                }
                if (r > 0 && (fds[0].revents & POLLIN) != 0) {
                    char buf[64];
                    while (read(wake_[0], buf, sizeof(buf)) > 0) {
                        // the doorbell, and nothing in it
                    }
                }
                if (n < 2 || (fds[1].revents & (POLLIN | POLLERR | POLLHUP)) == 0) {
                    continue;
                }
            }

            // processMsg() handles at most one message, so this loops until the
            // socket's buffer is empty or the queue needs draining.
            while (conn->processMsg()) {
                core::Timer::checkTimeouts();
                const std::lock_guard<std::mutex> guard(lock_);
                if (quit_ || !queue_.empty()) {
                    break;
                }
            }
        }
    } catch (rdr::end_of_stream &e) {
        detail = "The connection was lost";
    } catch (rfb::auth_cancelled &e) {
        detail = "";
    } catch (rfb::auth_error &e) {
        detail = std::string("Authentication failed: ") + e.what();
    } catch (std::exception &e) {
        detail = e.what();
    }

    bool asked;
    {
        const std::lock_guard<std::mutex> guard(lock_);
        asked = quit_;
    }
    if (conn) {
        try {
            conn->close();
        } catch (std::exception &) {
            // Already broken, and this is the goodbye.
        }
    }

    {
        // The reader may be inside readRegion; the framebuffer goes away with
        // the connection, so the copy it reads must stop existing first.
        const std::unique_lock<std::shared_mutex> guard(fbLock_);
        conn.reset();
        sock.reset();
        shadow_.clear();
        shadowW_ = shadowH_ = 0;
    }

    closed(asked && detail.empty() ? "" : (detail.empty() ? "The connection was lost" : detail));
    vm_->DetachCurrentThread();
}

// ---- pixels, from whichever thread is drawing ----------------------------

bool Session::readRegion(JNIEnv *env, int x, int y, int w, int h,
                         jobject bitmap, int dstX, int dstY) {
    AndroidBitmapInfo info;
    if (w <= 0 || h <= 0
            || AndroidBitmap_getInfo(env, bitmap, &info) != ANDROID_BITMAP_RESULT_SUCCESS
            || info.format != ANDROID_BITMAP_FORMAT_RGBA_8888
            || dstX < 0 || dstY < 0
            || (uint32_t) (dstX + w) > info.width || (uint32_t) (dstY + h) > info.height) {
        return false;
    }

    const std::shared_lock<std::shared_mutex> guard(fbLock_);
    if (shadow_.empty() || x < 0 || y < 0 || x + w > shadowW_ || y + h > shadowH_) {
        return false;
    }
    void *dst = nullptr;
    if (AndroidBitmap_lockPixels(env, bitmap, &dst) != ANDROID_BITMAP_RESULT_SUCCESS) {
        return false;
    }
    for (int row = 0; row < h; row++) {
        const uint32_t *src = shadow_.data() + (size_t) (y + row) * (size_t) shadowW_ + x;
        uint8_t *out = (uint8_t *) dst + (size_t) (dstY + row) * info.stride
                + (size_t) dstX * 4u;
        memcpy(out, src, (size_t) w * 4u);
    }
    AndroidBitmap_unlockPixels(env, bitmap);
    return true;
}

bool Session::readThumbnail(JNIEnv *env, int step, jobject bitmap) {
    AndroidBitmapInfo info;
    if (step < 1
            || AndroidBitmap_getInfo(env, bitmap, &info) != ANDROID_BITMAP_RESULT_SUCCESS
            || info.format != ANDROID_BITMAP_FORMAT_RGBA_8888) {
        return false;
    }

    const std::shared_lock<std::shared_mutex> guard(fbLock_);
    if (shadow_.empty()) {
        return false;
    }
    const int tw = (shadowW_ + step - 1) / step;
    const int th = (shadowH_ + step - 1) / step;
    if ((uint32_t) tw > info.width || (uint32_t) th > info.height) {
        return false;
    }
    void *dst = nullptr;
    if (AndroidBitmap_lockPixels(env, bitmap, &dst) != ANDROID_BITMAP_RESULT_SUCCESS) {
        return false;
    }
    for (int row = 0; row < th; row++) {
        const uint32_t *src = shadow_.data() + (size_t) (row * step) * (size_t) shadowW_;
        uint32_t *out = (uint32_t *) ((uint8_t *) dst + (size_t) row * info.stride);
        for (int col = 0; col < tw; col++) {
            out[col] = src[col * step];
        }
    }
    AndroidBitmap_unlockPixels(env, bitmap);
    return true;
}

jobjectArray Session::info(JNIEnv *env) {
    std::string desktop, protocol, security, serverPF, viewerPF;
    {
        const std::lock_guard<std::mutex> guard(infoLock_);
        desktop = infoDesktop_;
        protocol = infoProtocol_;
        security = infoSecurity_;
        serverPF = infoServerPF_;
        viewerPF = infoViewerPF_;
    }
    const int encoding = infoEncoding_;
    char speed[32];
    snprintf(speed, sizeof(speed), "%u kbit/s", infoLineSpeed_.load() / 1000);

    const char *values[] = {
            desktop.c_str(),
            protocol.c_str(),
            "TCP",
            security.c_str(),
            encoding < 0 ? "" : rfb::encodingName(encoding),
            speed,
            serverPF.c_str(),
            viewerPF.c_str(),
    };
    const int n = (int) (sizeof(values) / sizeof(values[0]));
    jobjectArray out = env->NewObjectArray(n, env->FindClass("java/lang/String"), nullptr);
    if (out == nullptr) {
        return nullptr;
    }
    for (int i = 0; i < n; i++) {
        // The desktop name is the server's, and their reader guarantees only
        // that it is valid UTF-8 — which a four-byte sequence makes exactly not
        // the modified UTF-8 NewStringUTF wants. The rest of these the library
        // printed.
        jstring js = i == 0 ? fromUtf8(env, values[i]) : env->NewStringUTF(values[i]);
        env->SetObjectArrayElement(out, i, js);
        env->DeleteLocalRef(js);
    }
    return out;
}

