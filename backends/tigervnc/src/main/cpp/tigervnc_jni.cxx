NATIVE(jlong, nativeCreate)(JNIEnv *env, jclass, jobject listener, jstring address,
                            jstring userName, jstring password, jboolean shared,
                            jboolean anonymousTls, jint encoding, jint compressLevel,
                            jint qualityLevel, jint colorLevel, jboolean h264,
                            jint connectTimeoutMs) {
    initLogging();
    if (gCallbacksClass == nullptr) {
        jclass k = env->GetObjectClass(listener);
        mConnected = env->GetMethodID(k, "onConnected", "(II)V");
        mDesktopSize = env->GetMethodID(k, "onDesktopSize", "(II)V");
        mDamage = env->GetMethodID(k, "onDamage", "(IIII)V");
        mFrameEnd = env->GetMethodID(k, "onFrameEnd", "()V");
        mCursor = env->GetMethodID(k, "onCursor", "([IIIIIJ)V");
        mBell = env->GetMethodID(k, "onBell", "()V");
        mClipboard = env->GetMethodID(k, "onClipboard", "(Ljava/lang/String;)V");
        mCredentialsNeeded = env->GetMethodID(k, "onCredentialsNeeded", "(Z)V");
        mQuestion = env->GetMethodID(k, "onQuestion", "(Ljava/lang/String;Ljava/lang/String;)V");
        mUnverified = env->GetMethodID(k, "onUnverified", "(Ljava/lang/String;)V");
        mClosed = env->GetMethodID(k, "onClosed", "(Ljava/lang/String;)V");
        // Last, and that is the point: it is what every other caller tests, so
        // publishing it first would let a second one past while the method ids
        // above were still zero.
        gCallbacksClass = (jclass) env->NewGlobalRef(k);
    }

    Session *s = new Session(env, listener, toString(env, address), toString(env, userName),
                             toString(env, password), shared != JNI_FALSE,
                             anonymousTls != JNI_FALSE, encoding, compressLevel,
                             qualityLevel, colorLevel, h264 != JNI_FALSE, connectTimeoutMs);
    if (!s->start()) {
        s->destroy();
        delete s;
        return 0;
    }
    return (jlong) (intptr_t) s;
}

NATIVE(void, nativeAnswerCredentials)(JNIEnv *env, jclass, jlong handle, jstring userName,
                                      jstring password) {
    Session *s = handleOf(handle);
    if (s != nullptr) {
        const std::string user = toString(env, userName);
        if (password == nullptr) {
            s->answerCredentials(user, nullptr);
        } else {
            const std::string secret = toString(env, password);
            s->answerCredentials(user, secret.c_str());
        }
    }
}

// TigerVNC finds its known-hosts file through the environment, whose HOME on
// Android is not a directory an app may write to. Both are set rather than one
// because the XDG variable is only consulted after a home directory is found —
// and what it names is the *parent*: the library's own directory under it is
// made here, since nothing in the library makes it and a store that fails is
// only a line in the log.
NATIVE(void, nativeSetStateDir)(JNIEnv *env, jclass, jstring path) {
    const std::string dir = toString(env, path);
    if (!dir.empty()) {
        setenv("XDG_STATE_HOME", dir.c_str(), 1);
        setenv("HOME", dir.c_str(), 0);
        mkdir((dir + "/tigervnc").c_str(), 0700);
    }
}

