/// As many commands as the other shim's ring holds, and bounded for the same
/// reason: nothing is drained until the connection is up.
constexpr size_t CMD_QUEUE_MAX = 512;

// What Android's ARGB_8888 is: four bytes per pixel, red first in memory. A
// little-endian pixel with red at shift 0 puts them in that order, which is
// what makes every read from the framebuffer a memcpy.
const rfb::PixelFormat androidPF(32, 24, false, true, 255, 255, 255, 0, 8, 16);

// The two reduced formats, which are their own viewer's low and very low
// colour and the same 64 and 8 colours the other backends' rows call rgb222 and
// rgb111. Only the wire changes: the decoders convert into the framebuffer,
// which stays androidPF, so nothing downstream of a decode knows about this.
const rfb::PixelFormat lowColourPF(8, 6, false, true, 3, 3, 3, 4, 2, 0);
const rfb::PixelFormat veryLowColourPF(8, 3, false, true, 1, 1, 1, 2, 1, 0);

/** Automatic, for a level or a quality: follow the measured line speed. */
constexpr int LEVEL_AUTO = -2;

/** Their thresholds, from the viewer: full colour above 256 kbit/s. */
const rfb::PixelFormat &colourPF(int level, unsigned bps) {
    switch (level) {
        case 1:
            return lowColourPF;
        case 2:
            return veryLowColourPF;
        case LEVEL_AUTO:
            return bps > 256000 ? androidPF : lowColourPF;
        default:
            return androidPF;
    }
}

/**
 * Above 16 Mbit/s — a LAN — the second highest JPEG quality, which should be
 * perceptually lossless; below it, a lossier one. Theirs, thresholds included.
 */
int qualityFor(int level, unsigned bps) {
    return level == LEVEL_AUTO ? (bps > 16000000 ? 8 : 6) : level;
}

