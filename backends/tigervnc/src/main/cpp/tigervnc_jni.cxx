// ---- the session ---------------------------------------------------------

class Session {
public:
    Session(JNIEnv *env, jobject callbacks, std::string address, std::string userName,
            std::string password, bool shared, bool anonymousTls, int encoding,
            int compressLevel, int qualityLevel, int colorLevel, bool h264,
            int connectTimeoutMs)
            : address_(std::move(address)), userName_(std::move(userName)),
              password_(std::move(password)), shared_(shared),
              anonymousTls_(anonymousTls), encoding_(encoding),
              compressLevel_(compressLevel), qualityLevel_(qualityLevel),
              colorLevel_(colorLevel), h264_(h264),
              connectTimeoutMs_(connectTimeoutMs) {
        env->GetJavaVM(&vm_);
        callbacks_ = env->NewGlobalRef(callbacks);
        if (pipe(wake_) == 0) {
            for (int fd : wake_) {
                fcntl(fd, F_SETFL, fcntl(fd, F_GETFL, 0) | O_NONBLOCK);
            }
        }
    }

    bool start() {
        if (wake_[0] < 0) {
            return false;
        }
        thread_ = std::thread([this] { run(); });
        return true;
    }

    void destroy() {
        disconnect();
        if (thread_.joinable()) {
            thread_.join();
        }
        const Env env(vm_);
        if (env) {
            env->DeleteGlobalRef(callbacks_);
        }
        close(wake_[0]);
        close(wake_[1]);
    }

    JavaVM *vm() { return vm_; }

    jobject callbacks() { return callbacks_; }

    // ---- calls from Java --------------------------------------------------

    void post(Cmd cmd) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            if (quit_) {
                return;
            }
            // Motion coalesces onto the tail of the queue: the protocol thread
            // can be inside a decode, and by the time it drains, every position
            // but the last is somewhere the pointer no longer is. A button
            // change is a different event and is never merged away.
            if (cmd.type == CMD_POINTER && !queue_.empty()
                    && queue_.back().type == CMD_POINTER && queue_.back().c == cmd.c) {
                queue_.back() = std::move(cmd);
            } else {
                // Bounded like the other shim's ring, and for the same reason:
                // nothing is drained until the connection is up, and answering
                // a password prompt can take as long as somebody likes. The
                // oldest goes, since the newest is what the far end still needs
                // to be told.
                if (queue_.size() >= CMD_QUEUE_MAX) {
                    queue_.pop_front();
                }
                queue_.push_back(std::move(cmd));
            }
        }
        wake();
    }

    void disconnect() {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            quit_ = true;
            paused_ = false;
        }
        answered_.notify_all();
        wake();
        // The doorbell is only looked at between messages, and a read that has
        // started blocks inside their stream until the rest of the message
        // arrives — so a server that accepts the connection and then stalls
        // would hold whoever called destroy(), which is the main thread. The
        // descriptor stays TcpSocket's; only the shutdown is ours.
        const int fd = fd_.load();
        if (fd >= 0) {
            ::shutdown(fd, SHUT_RDWR);
        }
    }

    // Stop reading the socket, which in the other two RFB backends is the whole
    // pause: an RFB server sends nothing that was not asked for, so leaving the
    // last update unread is what makes it wait. Not here — this client turns
    // continuous updates on, so the server pushes without being asked. What
    // stops it instead is TigerVNC's own congestion control: it sends fences
    // and waits for the replies, which a client that is not reading does not
    // send. Same effect, different mechanism, and worth knowing before
    // measuring a backgrounded session against the other two.
    void setFocus(bool focused) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            paused_ = !focused;
        }
        wake();
    }

    void setViewOnly(bool viewOnly) { viewOnly_ = viewOnly; }

    bool viewOnly() const { return viewOnly_; }

    /** Set from the protocol thread, read from whichever asks. */
    void setCanResize(bool can) { canResize_ = can; }

    /** The far end's screen layout, flattened four ints per screen. */
    void setScreens(std::vector<jint> screens) {
        const std::lock_guard<std::mutex> guard(screensLock_);
        screens_ = std::move(screens);
    }

    std::vector<jint> screens() const {
        const std::lock_guard<std::mutex> guard(screensLock_);
        return screens_;
    }

    void setConnected() {
        const std::lock_guard<std::mutex> guard(lock_);
        connected_ = true;
    }

    /* More than one screen says no, and that is the shim's limitation rather
       than the library's: what a resize sends is a single screen covering the
       desktop, so granting one would merge somebody's monitors into one. */
    bool canResize() const {
        if (!canResize_ || viewOnly_) {
            return false;
        }
        const std::lock_guard<std::mutex> guard(screensLock_);
        return screens_.size() <= 4;
    }

    void answerCredentials(const std::string &user, const char *password) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            credUser_ = user;
            credPassword_ = password ? password : "";
            credCancelled_ = password == nullptr;
            credAnswered_ = true;
            if (credCancelled_) {
                quit_ = true;
            }
        }
        answered_.notify_all();
        wake();
    }

    /** Blocks the protocol thread until Java answers: a dialog and a person. */
    bool askCredentials(bool needsUserName, std::string *user, std::string *password) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            credAnswered_ = false;
        }
        const Env env(vm_);
        if (env) {
            env->CallVoidMethod(callbacks_, mCredentialsNeeded, (jboolean) needsUserName);
            cleared(env.get());
        }
        std::unique_lock<std::mutex> guard(lock_);
        answered_.wait(guard, [this] { return credAnswered_ || quit_; });
        if (credCancelled_ || quit_) {
            return false;
        }
        if (user != nullptr) {
            *user = credUser_;
        }
        *password = credPassword_;
        return true;
    }

    void answerQuestion(bool yes) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            questionYes_ = yes;
            questionAnswered_ = true;
            if (!yes) {
                quit_ = true;
            }
        }
        answered_.notify_all();
        wake();
    }

    /** Blocks the protocol thread, as the credentials prompt does. */
    bool askQuestion(const char *title, const char *text) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            questionAnswered_ = false;
        }
        const Env env(vm_);
        if (env) {
            jstring jTitle = fromUtf8(env.get(), title);
            jstring jText = fromUtf8(env.get(), text);
            env->CallVoidMethod(callbacks_, mQuestion, jTitle, jText);
            cleared(env.get());
            env->DeleteLocalRef(jTitle);
            env->DeleteLocalRef(jText);
        }
        std::unique_lock<std::mutex> guard(lock_);
        answered_.wait(guard, [this] { return questionAnswered_ || quit_; });
        return questionYes_ && !quit_;
    }

    /** The same wait again, for a far end with no identity to show at all. */
    bool askUnverified(const char *why) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            questionAnswered_ = false;
        }
        const Env env(vm_);
        if (env) {
            jstring jWhy = fromUtf8(env.get(), why);
            env->CallVoidMethod(callbacks_, mUnverified, jWhy);
            cleared(env.get());
            env->DeleteLocalRef(jWhy);
        }
        std::unique_lock<std::mutex> guard(lock_);
        answered_.wait(guard, [this] { return questionAnswered_ || quit_; });
        return questionYes_ && !quit_;
    }

    bool anonymousTls() const { return anonymousTls_; }

    void setPicture(int encoding, int compressLevel, int qualityLevel, int colorLevel,
                    bool h264) {
        const std::lock_guard<std::mutex> guard(lock_);
        encoding_ = encoding;
        compressLevel_ = compressLevel;
        qualityLevel_ = qualityLevel;
        colorLevel_ = colorLevel;
        h264_ = h264;
    }

    /** Only ever the protocol thread's, and only between messages. */
    void applyPicture(Conn *conn) {
        // The settings are copied out and the lock released before anything is
        // said to the connection: refreshFramebuffer can write and flush, which
        // blocks on a server that has stopped reading, and this is the mutex
        // every touch event and destroy() takes.
        int encoding, compressLevel, qualityLevel, colorLevel;
        bool h264;
        {
            const std::lock_guard<std::mutex> guard(lock_);
            encoding = encoding_;
            compressLevel = compressLevel_;
            qualityLevel = qualityLevel_;
            colorLevel = colorLevel_;
            h264 = h264_;
        }
        // Before the preference, which is one of the things that re-sends
        // SetEncodings: this decides whether H.264 is in the list at all, and
        // asking for it as a preference while it is not offered would leave the
        // server the encoding it already had. It marks the list changed itself,
        // because otherwise moving this row alone re-sends nothing.
        conn->offerH264(h264);
        conn->setPreferredEncoding(encoding);
        conn->setCompressLevel(compressLevel);
        const int quality = qualityFor(qualityLevel, conn->bandwidth());
        // Tight's JPEG is enabled by there being a quality level at all, so
        // lossless is the absence of one rather than a value of it. On the
        // connection rather than on the library's global parameter, which is a
        // patch of ours: two sessions at different qualities would otherwise
        // each be deciding the other's encoding list.
        conn->setNoJpeg(quality < 0);
        conn->setQualityLevel(quality);
        // Safe at any moment, which is the library's doing rather than ours:
        // their setPF only records the format, and the connection switches to it
        // where nothing is in flight — for continuous updates by stopping them
        // and waiting for the end-of-continuous-updates message. libvncclient
        // has no such point, which is why the same row is not live there.
        const rfb::PixelFormat &pf = colourPF(colorLevel, conn->bandwidth());
        if (!requestedPF_ || !(*requestedPF_ == pf)) {
            requestedPF_ = pf;
            conn->setPF(pf);
            setViewerPF(pf);
            // A format decides how the *next* rectangle arrives, and a desktop
            // that is not changing sends none — so the whole picture is asked
            // for again, or moving this row does nothing anybody can see. Their
            // own refresh, which knows to wait where an update is in flight.
            conn->refreshFramebuffer();
        }
    }

    /** Whether anything about the picture follows the measured line speed. */
    bool picturesItself() {
        const std::lock_guard<std::mutex> guard(lock_);
        return qualityLevel_ == LEVEL_AUTO || colorLevel_ == LEVEL_AUTO;
    }

    /** The copy the drawing thread reads, and the only pixels it may see. */
    bool readRegion(JNIEnv *env, int x, int y, int w, int h,
                    jobject bitmap, int dstX, int dstY);

    bool readThumbnail(JNIEnv *env, int step, jobject bitmap);

    jobjectArray info(JNIEnv *env);

    // ---- called from the connection (protocol thread) ---------------------

    void resized(int w, int h, bool first) {
        {
            const std::unique_lock<std::shared_mutex> guard(fbLock_);
            shadow_.assign((size_t) w * (size_t) h, 0xFF000000u);
            shadowW_ = w;
            shadowH_ = h;
        }
        const Env env(vm_);
        if (env) {
            env->CallVoidMethod(callbacks_, first ? mConnected : mDesktopSize, w, h);
            cleared(env.get());
        }
    }

    /** The whole of the second framebuffer's cost, and the only place it is
        paid: once per damaged rectangle per update, under the writer lock. */
    void publish(Framebuffer *fb, const std::vector<core::Rect> &rects) {
        {
            const std::unique_lock<std::shared_mutex> guard(fbLock_);
            for (const core::Rect &r : rects) {
                int stride = 0;
                const uint8_t *src = fb->getBuffer(r, &stride);
                for (int row = 0; row < r.height(); row++) {
                    const uint32_t *in = (const uint32_t *) src + (size_t) row * stride;
                    uint32_t *out = shadow_.data()
                            + (size_t) (r.tl.y + row) * (size_t) shadowW_ + r.tl.x;
                    for (int col = 0; col < r.width(); col++) {
                        out[col] = in[col] | 0xFF000000u;
                    }
                }
            }
        }
        const Env env(vm_);
        if (env) {
            for (const core::Rect &r : rects) {
                env->CallVoidMethod(callbacks_, mDamage, r.tl.x, r.tl.y, r.width(), r.height());
                cleared(env.get());
            }
            env->CallVoidMethod(callbacks_, mFrameEnd);
            cleared(env.get());
        }
    }

    void closed(const std::string &detail) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            if (closedReported_) {
                return;
            }
            closedReported_ = true;
        }
        const Env env(vm_);
        if (env) {
            // Through the converter, not NewStringUTF: an auth_error's text
            // quotes the reason string the *server* sent, so these are not
            // bytes this file chose.
            jstring d = fromUtf8(env.get(), detail.c_str());
            env->CallVoidMethod(callbacks_, mClosed, d);
            cleared(env.get());
            env->DeleteLocalRef(d);
        }
    }

    std::string storedUser() const { return userName_; }

    std::string takeStoredPassword() {
        std::string p = password_;
        password_.clear();
        return p;
    }

    const std::string &pendingClipboard() const { return clipboardOut_; }

private:
    void run();

    void wake() {
        const char one = 1;
        (void) !write(wake_[1], &one, 1);
    }

    /** Non-blocking connect with a deadline, and the descriptor is the result. */
    int openSocket(std::string *why);

    const std::string address_;
    const std::string userName_;
    std::string password_;
    const bool shared_;
    const bool anonymousTls_;
    int encoding_;
    int compressLevel_;
    int qualityLevel_;
    int colorLevel_;
    // The format last asked for, which is not the connection's until it has
    // somewhere safe to switch — so the comparison that decides whether
    // anything changed has to be against this rather than against server.pf().
    std::optional<rfb::PixelFormat> requestedPF_;
    bool h264_;
    const int connectTimeoutMs_;

    JavaVM *vm_ = nullptr;
    jobject callbacks_ = nullptr;
    std::thread thread_;
    int wake_[2] = {-1, -1};
    std::atomic<int> fd_{-1}; // the socket's, for disconnect(); owned by TcpSocket

    std::mutex lock_;
    std::condition_variable answered_;
    std::deque<Cmd> queue_;
    bool quit_ = false;
    bool paused_ = false;
    bool closedReported_ = false;
    bool connected_ = false;
    bool credAnswered_ = false;
    bool credCancelled_ = false;
    bool questionAnswered_ = false;
    bool questionYes_ = false;
    std::string credUser_;
    std::string credPassword_;
    std::string clipboardOut_;
    std::atomic<bool> viewOnly_{false};
    std::atomic<bool> canResize_{false};
    mutable std::mutex screensLock_;
    std::vector<jint> screens_;

    std::shared_mutex fbLock_;
    std::vector<uint32_t> shadow_;
    int shadowW_ = 0;
    int shadowH_ = 0;

    std::string serverHost_;
    int serverPort_ = 0;

    // The facts the panel asks for, kept where anyone can read them rather than
    // fetched: every one of them lives in the connection, which only the
    // protocol thread may touch, and it can be inside a decode or behind an
    // unanswered password prompt when the question arrives.
    std::mutex infoLock_;
    std::string infoDesktop_, infoProtocol_, infoSecurity_, infoServerPF_, infoViewerPF_;
    std::atomic<int> infoEncoding_{-1};
    std::atomic<unsigned> infoLineSpeed_{0};
    std::atomic<jlong> infoReceived_{-1}, infoSent_{-1};

public:
    void setConnectionFacts(const std::string &desktop, const std::string &protocol,
                            const std::string &security, const std::string &serverPF) {
        const std::lock_guard<std::mutex> guard(infoLock_);
        infoDesktop_ = desktop;
        infoProtocol_ = protocol;
        infoSecurity_ = security;
        infoServerPF_ = serverPF;
    }

    void setDesktopName(const std::string &desktop) {
        const std::lock_guard<std::mutex> guard(infoLock_);
        infoDesktop_ = desktop;
    }

    void setLiveFacts(int encoding, unsigned lineSpeed) {
        infoEncoding_ = encoding;
        infoLineSpeed_ = lineSpeed;
    }

    /** What the connection's own two streams have carried, published from the
        protocol thread because they may only be read there. Both are the
        connection's rather than the socket's, so this is the protocol inside
        whatever is encrypting it. */
    void setTraffic(jlong received, jlong sent) {
        infoReceived_ = received;
        infoSent_ = sent;
    }

    void traffic(jlong *out) const {
        out[0] = infoReceived_.load();
        out[1] = infoSent_.load();
    }

    /** What was last asked for on the wire, which is not the framebuffer's. */
    void setViewerPF(const rfb::PixelFormat &pf) {
        char text[100];
        pf.print(text, sizeof(text));
        const std::lock_guard<std::mutex> guard(infoLock_);
        infoViewerPF_ = text;
    }

private:
    void runCmd(Conn *conn, Cmd &cmd);
};

// ---- Conn, which is where the protocol reaches the session ---------------

void Conn::newFramebuffer(int w, int h) {
    setFramebuffer(new Framebuffer(w, h));
}

void Conn::initDone() {
    // The server's own format, read before anything is asked for: after setPF
    // this is whatever we asked for, which is the other row.
    char pf[100];
    server.pf().print(pf, sizeof(pf));

    s->applyPicture(this);
    newFramebuffer(server.width(), server.height());

    char protocol[32];
    snprintf(protocol, sizeof(protocol), "RFB %d.%d", server.majorVersion, server.minorVersion);
    // Their own name for the type, and for the three with no certificate under
    // them what that leaves: a session saying only "TLSVnc" would be claiming
    // the identity check this family does not have.
    std::string security;
    if (csecurity != nullptr) {
        const int type = csecurity->getType();
        security = rfb::secTypeName(type);
        if (type == rfb::secTypeTLSNone || type == rfb::secTypeTLSVnc
            || type == rfb::secTypeTLSPlain) {
            security += ", encrypted and unverified";
        }
    }
    s->setConnectionFacts(server.name(), protocol, security.c_str(), pf);

    s->resized(server.width(), server.height(), true);
    s->setConnected();
}

void Conn::setName(const char *name) {
    rfb::CConnection::setName(name);
    s->setDesktopName(server.name());
}

// Called for every desktop-size rectangle, which a server sends at the head of
// every *non-incremental* update — so this is only a resize when the size has
// actually changed, and treating it as one otherwise asks for a full update
// that provokes the next one.
void Conn::resizeFramebuffer() {
    if (framebuffer() != nullptr && framebuffer()->width() == server.width()
            && framebuffer()->height() == server.height()) {
        return;
    }
    newFramebuffer(server.width(), server.height());
    s->resized(server.width(), server.height(), false);
    // Nothing survives the reallocation, so ask for all of it.
    refreshFramebuffer();
}

// The library's own handler sets server.supportsSetDesktopSize and, where the
// answer is yes, the new size — which reaches Java through resizeFramebuffer
// like any other. What is added here is the flag Java may read at any moment,
// and the one thing the library does not carry out of the protocol thread: the
// result code, which is the only place a refusal is stated at all.
void Conn::setExtendedDesktopSize(unsigned reason, unsigned result, int w, int h,
                                  const rfb::ScreenSet &layout) {
    rfb::CConnection::setExtendedDesktopSize(reason, result, w, h, layout);
    s->setCanResize(true);
    // The rectangle's own layout rather than server.screenLayout(), which the
    // base class leaves at the old one when the server has said no.
    std::vector<jint> screens;
    screens.reserve(layout.num_screens() * 4);
    for (const rfb::Screen &screen : layout) {
        screens.push_back(screen.dimensions.tl.x);
        screens.push_back(screen.dimensions.tl.y);
        screens.push_back(screen.dimensions.width());
        screens.push_back(screen.dimensions.height());
    }
    s->setScreens(std::move(screens));
    if (reason == rfb::reasonClient && result != rfb::resultSuccess) {
        // Not the size that was asked for: a refusal carries the size the
        // desktop still has, which is the one thing this rectangle is sure to
        // say. 1 is prohibited, 2 out of resources, 3 an invalid layout.
        LOGW("the server refused a resize and stayed at %dx%d (result %u)", w, h, result);
    }
}

void Conn::framebufferUpdateStart() {
    rfb::CConnection::framebufferUpdateStart();
    gettimeofday(&updateStartTime, nullptr);
    updateStartPos = getInStream()->pos();
}

void Conn::framebufferUpdateEnd() {
    rfb::CConnection::framebufferUpdateEnd();

    struct timeval now;
    gettimeofday(&now, nullptr);
    unsigned long long elapsed = (now.tv_sec - updateStartTime.tv_sec) * 1000000ull;
    elapsed += now.tv_usec - updateStartTime.tv_usec;
    if (elapsed == 0) {
        elapsed = 1;
    }
    const unsigned long long bps =
            (unsigned long long) (getInStream()->pos() - updateStartPos) * 8 * 1000000 / elapsed;
    unsigned long long weight = elapsed; // µs: upstream's fraction of a second, in millionths
    if (weight > 200000) {
        weight = 200000;
    }
    bpsEstimate = (unsigned) (((unsigned long long) bpsEstimate * (1000000 - weight)
            + bps * weight) / 1000000);
    s->setLiveFacts(lastServerEncoding, bpsEstimate);

    // Where anything about the picture follows the line speed, this is where
    // the viewer moves it too: the estimate has just changed, and setting a
    // quality or a format here only marks it — both go out with the request for
    // the next update rather than into the middle of this one.
    if (s->picturesItself()) {
        s->applyPicture(this);
    }

    Framebuffer *fb = framebuffer();
    if (fb == nullptr) {
        return;
    }
    core::Region damage = fb->takeDamage();
    std::vector<core::Rect> rects;
    damage.get_rects(&rects);
    if (!rects.empty()) {
        s->publish(fb, rects);
    }
}

bool Conn::dataRect(const core::Rect &r, int encoding) {
    if (encoding != rfb::encodingCopyRect) {
        lastServerEncoding = encoding;
    }
    return rfb::CConnection::dataRect(r, encoding);
}

/* FNV-1a over a cursor's pixels, which is its identity in CursorCache — so
   this, the other shims' copies of it and the Java one all have to agree.
   Computed while the pixels are still hot from the conversion above; what it
   saves on the other side is a bitmap and a texture per cursor change. */
static jlong cursorHash(const jint *argb, int width, int height) {
    uint64_t h = 0xcbf29ce484222325ull;
    h = (h ^ (uint32_t) width) * 0x100000001b3ull;
    h = (h ^ (uint32_t) height) * 0x100000001b3ull;
    for (int i = 0; i < width * height; i++) {
        h = (h ^ (uint32_t) argb[i]) * 0x100000001b3ull;
    }
    return (jlong) h;
}

void Conn::setCursor(int width, int height, const core::Point &hotspot,
                     const uint8_t *data) {
    rfb::CConnection::setCursor(width, height, hotspot, data);

    const Env env(s->vm());
    if (!env) {
        return;
    }
    jintArray argb = nullptr;
    jlong hash = 0;
    if (width > 0 && height > 0 && data != nullptr) {
        argb = env->NewIntArray(width * height);
        if (argb != nullptr) {
            jint *out = env->GetIntArrayElements(argb, nullptr);
            // Four bytes a pixel, red first — the order the cursor readers
            // write whichever encoding carried it.
            for (int i = 0; i < width * height; i++) {
                out[i] = (jint) (((uint32_t) data[i * 4 + 3] << 24)
                        | ((uint32_t) data[i * 4] << 16)
                        | ((uint32_t) data[i * 4 + 1] << 8)
                        | (uint32_t) data[i * 4 + 2]);
            }
            hash = cursorHash(out, width, height);
            env->ReleaseIntArrayElements(argb, out, 0);
        }
    }
    env->CallVoidMethod(s->callbacks(), mCursor, argb, width, height, hotspot.x, hotspot.y, hash);
    cleared(env.get());
    if (argb != nullptr) {
        env->DeleteLocalRef(argb);
    }
}

void Conn::bell() {
    const Env env(s->vm());
    if (env) {
        env->CallVoidMethod(s->callbacks(), mBell);
        cleared(env.get());
    }
}

void Conn::getUserPasswd(bool /*secure*/, std::string *user, std::string *password) {
    const std::string stored = s->takeStoredPassword();
    if (!stored.empty()) {
        if (user != nullptr) {
            *user = s->storedUser();
        }
        *password = stored;
        return;
    }
    // A cancelled prompt is a cancelled connection, and saying so as their own
    // exception is what stops the handshake from carrying on with an empty one.
    if (!s->askCredentials(user != nullptr, user, password)) {
        throw rfb::auth_cancelled();
    }
}

// Every one of these is about the far end's identity — an RSA-AES key
// fingerprint, or a certificate that verified against nothing — so the answer
// is a person's and the handshake waits for it.
bool Conn::showMsgBox(rfb::MsgBoxFlags /*flags*/, const char *title, const char *text) {
    return s->askQuestion(title, text);
}

// The tunnel came up with no certificate under it, which is a different
// question from whether an identity is the right one: there is nothing to show
// and nothing to remember, so it is asked in the app's own words every time.
//
// The refusal is here rather than in the offer because the type list is one
// string for the process: the sub-types are always offered and a connection
// that does not want them says so at this point, one handshake later than it
// would like and before anything has been authenticated inside it.
void Conn::confirmAnonymousTLS() {
    if (!s->anonymousTls()) {
        throw std::runtime_error(
                "This server only offers encryption without a peer certificate, which is not enabled for this connection.");
    }
    if (!s->askUnverified("This server offers encryption without a peer certificate.")) {
        throw rfb::auth_cancelled();
    }
}

