//! With the `c` feature, generates Rust bindings for `src/c/ffi.rs` from
//! `vento/backend.h`, `vento/video.h`, `vento/audio.h`, `vento/net.h` and
//! `vento/text.h`
//! (only its constants: its functions are inline and the Rust side has its
//! own) in this crate's `include/`.
//!
//! The vtable's member order is the ABI, and a hand-written `#[repr(C)]`
//! copy would drift the first time a header changed. The headers are ours,
//! small and C, and every item wanted is named `vento_` or `VENTO_`.
//!
//! Only the shared headers are generated here. Each C backend's own header,
//! `vento/<name>.h` in its module, is generated by that backend's crate on
//! top of these declarations, so that `vento_session` is the same Rust type
//! in every crate.

fn main() {
    #[cfg(feature = "c")]
    generate_bindings();
}

#[cfg(feature = "c")]
fn generate_bindings() {
    use std::env;
    use std::path::PathBuf;

    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let include = manifest.join("include");
    println!("cargo:rerun-if-changed={}", include.display());
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let bindings = bindgen::Builder::default()
        .header_contents(
            "vento.h",
            "#include <vento/backend.h>\n\
             #include <vento/video.h>\n\
             #include <vento/audio.h>\n\
             #include <vento/net.h>\n\
             #include <vento/text.h>\n",
        )
        .clang_arg(format!("-I{}", include.display()))
        .allowlist_item("vento_.*")
        .allowlist_item("VENTO_.*")
        // The inline wrappers call through the vtable, which the Rust side
        // does itself. `vento_strings_free` calls `free` on each item; the
        // Rust side does the same with libc's `free` so the allocator
        // matches.
        .generate_inline_functions(false)
        .derive_default(true)
        .layout_tests(false)
        .generate()
        .expect("bindgen over vento/backend.h");
    bindings
        .write_to_file(out.join("bindings.rs"))
        .expect("writing bindings.rs");
}
