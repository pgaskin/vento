vento_session *vento_realvnc_create(const vento_realvnc_config *cfg,
                                    const vento_callbacks *cb) {
    if (!cfg->address || !cfg->address[0]) {
        LOGW("no address");
        return nullptr;
    }
    CoreThread &core = CoreThread::instance();
    if (!core.core()) {
        if (!cfg->library_dir || !cfg->state_dir) {
            LOGW("the first session needs library_dir and state_dir");
            return nullptr;
        }
        // The hashes first, before a byte of either file is mapped.
        if (!verifyLibraries(cfg->library_dir)) {
            return nullptr;
        }
        mkdir(cfg->state_dir, 0700);
        struct stat st;
        if (stat(cfg->state_dir, &st) != 0 || !S_ISDIR(st.st_mode)) {
            LOGW("%s: not a directory", cfg->state_dir);
            return nullptr;
        }
        std::string why;
        if (!core.start(cfg->library_dir, bootstrapFor(cfg->state_dir), &why)) {
            LOGW("the core could not be brought up: %s", why.c_str());
            return nullptr;
        }
        LOGI("core initialised");
    }
    // Empty is not a password: the core authenticates with whatever it is
    // given, so "" fails the connection outright instead of asking.
    Session *s = new Session(*cb, *cfg, optionsFor(*cfg));
    s->start();
    return s;
}

