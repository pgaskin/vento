    /* The core pulls the local clipboard through `getClipboard` (at
       `createSession`, at `connSuccess`, and when focus returns) rather than
       having it pushed, so there is nothing to send: it is stored and returned
       when asked for. The focus is toggled so that text set mid-session
       reaches the far end immediately rather than at the next real focus
       change, which on a desktop may never come. */
    void clipboard(const char *utf8) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            clipboard_ = utf8;
            hasClipboard_ = true;
        }
        onSession([](HostedSession *hs) {
            hs->focusEvent(false);
            hs->focusEvent(true);
        });
    }

    /* As `RealVncBackend.setOption`: which keys need the second call
       (`applyOptions`) is a fact about this library, and the quality group is
       sent together, colour depth first and quality last, the order found to
       work. */
    void setOption(const std::string &key, const std::string &value) {
        Options alsoSet;
        {
            const std::lock_guard<std::mutex> guard(lock_);
            put(&options_, key, value);
            // Same rule as the constructor's: a depth set explicitly, before
            // the session or during it, is kept.
            colorLevelPinned_ = colorLevelPinned_ || key == "ColorLevel";
            if (needsApply(key)) {
                if (!colorLevelPinned_ && key == "Quality") {
                    put(&options_, "ColorLevel", colorLevelFor(value));
                }
                alsoSet.emplace_back("ColorLevel", get(options_, "ColorLevel", "full"));
                alsoSet.emplace_back("PreferredEncoding",
                                     get(options_, "PreferredEncoding", "ZRLE2"));
                alsoSet.emplace_back("Quality", get(options_, "Quality", "Auto"));
            } else {
                alsoSet.emplace_back(key, value);
            }
        }
        const bool group = needsApply(key);
        onSession([alsoSet, group](HostedSession *hs) {
            for (const auto &kv : alsoSet) {
                hs->setOption(kv.first, kv.second);
            }
            if (group) {
                hs->applyOptions();
            }
        });
    }

    /* Everything `ConnectionInfoBindings` reports, gathered on the core
       thread. Two of the strings change over time, so a panel polls rather
       than taking one snapshot. */
    bool info(vento_strings *out) {
        bool ok = false;
        CoreThread::instance().runBlocking([&] {
            HostedSession *hs = hs_.load();
            if (!hs || dead_.load() || state() != State::Connected) {
                return;
            }
            // Sampled here as well as on every update, since an idle desktop
            // can be seconds past the last one.
            sampleTraffic(hs);
            const std::string rows[] = {
                    hs->info(Info::DesktopName),       hs->info(Info::ProtoVersion),
                    hs->info(Info::ConnectionType),    hs->info(Info::SecurityDesc),
                    hs->info(Info::LastUsedEncoding),  hs->info(Info::LineSpeed),
                    hs->info(Info::ServerPixelFormat), hs->info(Info::ViewerPixelFormat),
            };
            const char *values[8];
            for (int i = 0; i < 8; i++) {
                values[i] = rows[i].c_str();
            }
            ok = vento_strings_set(out, values, 8);
        });
        return ok;
    }

    bool traffic(uint64_t out[2]) {
        const std::lock_guard<std::mutex> guard(trafficLock_);
        if (!trafficAgreed_ || trafficGaveUp_) {
            return false;
        }
        out[0] = (uint64_t) trafficTotal_;
        out[1] = 0; // the core counts one direction; vento/realvnc.h says so
        return true;
    }

    // ---- pixels, from the drawing thread --------------------------------------

    /* All pixels from this library come through `copyScaledRegion`, which
       writes the region to the front of a buffer the core owns, at that
       buffer's row stride. So the buffer is kept exactly the region's width,
       and the rows are copied out into place, with the alpha byte filled in
       as `vento/backend.h` requires. */
    bool readRegion(int x, int y, int w, int h, void *dst, size_t stride, int dstX, int dstY) {
        if (w <= 0 || h <= 0 || x < 0 || y < 0 || dstX < 0 || dstY < 0) {
            return false;
        }
        const std::lock_guard<std::mutex> guard(pixels_);
        HostedSession *hs = hs_.load();
        int dw, dh;
        {
            const std::lock_guard<std::mutex> g(lock_);
            dw = width_;
            dh = height_;
        }
        // Subtracted rather than added, so that `x + w` cannot overflow.
        if (!hs || dead_.load() || dw <= 0 || x > dw || y > dh || w > dw - x || h > dh - y) {
            return false;
        }
        if (!ensureBuffer(hs, w, h) || !hs->copyScaledRegion(x, y, w, h, 1.0f)) {
            return false;
        }
        copyOut(dst, stride, dstX, dstY, w, h);
        return true;
    }

    /* The core's scaler at `1/step`: its step is `(int)(1/scale)`, and the
       float passed is chosen so that both a float and a double reciprocal
       truncate to exactly `step`. 1/3 as a float is 0.33333334, whose
       reciprocal is 2.9999999, a step of two, which walks the source at half
       the stride the buffer was sized for and crashes in native code on the
       way out. The Android backend avoids this by using only powers of two;
       this one nudges the float down until the arithmetic agrees. */
    bool readThumbnail(int step, void *dst, size_t stride, int dstW, int dstH) {
        if (step < 1) {
            return false;
        }
        const std::lock_guard<std::mutex> guard(pixels_);
        HostedSession *hs = hs_.load();
        int w, h;
        {
            const std::lock_guard<std::mutex> g(lock_);
            w = width_;
            h = height_;
        }
        if (!hs || dead_.load() || w <= 0 || h <= 0) {
            return false;
        }
        const int tw = (w + step - 1) / step, th = (h + step - 1) / step;
        if (tw > dstW || th > dstH) {
            return false;
        }
        float scale = 1.0f / (float) step;
        while ((int) (1.0f / scale) < step || (int) (1.0 / (double) scale) < step) {
            scale = std::nextafter(scale, 0.0f);
        }
        if (!ensureBuffer(hs, tw, th) || !hs->copyScaledRegion(0, 0, w, h, scale)) {
            return false;
        }
        copyOut(dst, stride, 0, 0, tw, th);
        return true;
    }

    // ---- the answers, from any thread ---------------------------------------

    void answerCredentials(const char *user, const char *password) {
        const std::string u = user ? user : "";
        const bool ok = password != nullptr;
        const std::string p = password ? password : "";
        CoreThread::instance().post([this, u, ok, p] {
            if (passwdCookie_ == 0) {
                return;
            }
            const int64_t cookie = passwdCookie_;
            passwdCookie_ = 0;
            promptAnswered();
            // An empty name is the one the prompt proposed, so a platform
            // that only has a password to give does not blank the user.
            const std::string &name = u.empty() ? proposedUser_ : u;
            CoreThread::instance().core()->passwdResult(cookie, ok, ok ? name.c_str() : nullptr,
                                                        ok ? p.c_str() : nullptr);
        });
    }

    void answerTrust(bool accept) {
        CoreThread::instance().post([this, accept] {
            if (asks_.empty()) {
                return;
            }
            const auto ask = asks_.front();
            asks_.pop_front();
            promptAnswered();
            HostedCore *core = CoreThread::instance().core();
            if (ask.first == Ask::Security) {
                core->securityResult(ask.second, accept, false, false);
            } else {
                core->msgBoxResult(ask.second, accept);
            }
        });
    }

    void answerSecurity(bool accept, bool remember) {
        CoreThread::instance().post([this, accept, remember] {
            for (auto it = asks_.begin(); it != asks_.end(); ++it) {
                if (it->first == Ask::Security) {
                    const int64_t cookie = it->second;
                    asks_.erase(it);
                    promptAnswered();
                    // The two save flags are identity and encryption; the
                    // encryption decision is not one to remember silently,
                    // so only the identity is offered.
                    CoreThread::instance().core()->securityResult(cookie, accept, remember, false);
                    return;
                }
            }
        });
    }

    char *identitySaved() {
        const std::lock_guard<std::mutex> guard(lock_);
        return identity_.empty() ? nullptr : strdup(identity_.c_str());
    }

    // ---- lifecycle ---------------------------------------------------------

    /* As `RealVncBackend.disconnect`: closes the session *and* retires the
       handle, which prevents a second close. */
    void disconnect() {
        asked_.store(true);
        if (hs_.load()) {
            reap(true);
        } else {
            CoreThread::instance().post([this] { closed(""); });
        }
    }

    /* Retires the session from the core thread and returns once nothing of
       it can run there: the handle is dropped, the close is sent if the core
       has not already reported it closed, a `closed` not yet sent is
       delivered (it is the last callback, and this is the last chance), and
       the bridge the core still holds is cut off. The thread itself is not
       stopped: it is the core's and shared, and the core keeps the session;
       what is leaked is the core's (rule 3). */
    void destroy() {
        dead_.store(true);
        asked_.store(true);
        reap(true);
        // A short wait for the core's own `sessionClosed` to follow the
        // close, so that the session ends the usual way; the platform's own
        // wait for `closed` comes before this, as the probe's does.
        {
            std::unique_lock<std::mutex> guard(lock_);
            closedCv_.wait_for(guard, std::chrono::seconds(2), [this] { return closedSent_; });
        }
        CoreThread::instance().runBlocking([this] {
            closed("");
            bridge_->retire();
            // Last, where nothing can arm it again: a prompt answered while
            // this task was queued could have re-armed it, and a timeout left
            // running would fire into a session that is gone.
            CoreThread::instance().cancel(connectTimeout_);
        });
    }

    // ---- from the bridge, on the core thread ----------------------------------

    void onConnSuccess() {
        LOGI("connSuccess");
        // The connect is over: let the next waiting session begin.
        finishConnect();
        CoreThread::instance().cancel(connectTimeout_);
        // An error the core showed before this point (a wrong password,
        // asked again) is not the reason the session ends later.
        lastError_.clear();
        int w, h;
        {
            const std::lock_guard<std::mutex> guard(lock_);
            state_ = State::Connected;
            w = width_;
            h = height_;
        }
        cb_.connected(cb_.user, w, h);
    }

    void onDesktopSize(int width, int height) {
        LOGI("setDesktopSize %dx%d", width, height);
        bool connected;
        {
            const std::lock_guard<std::mutex> guard(lock_);
            width_ = width;
            height_ = height;
            connected = state_ == State::Connected;
        }
        // Before `connSuccess`, the size is reported by `connected`.
        if (connected) {
            cb_.desktop_size(cb_.user, width, height);
        }
    }

    void onDrawRegion(int x, int y, int width, int height) {
        cb_.damaged(cb_.user, x, y, width, height);
    }

    void onFrameEnd() {
        // The received count is sampled here, because this is the edge that
        // moves it: the estimator's window is the update this call ends. Once
        // a second is enough: the mark is cumulative, so a skipped update
        // loses nothing.
        const int64_t now = std::chrono::duration_cast<std::chrono::milliseconds>(
                                    std::chrono::steady_clock::now().time_since_epoch())
                                    .count();
        if (now - lastSample_ >= SAMPLE_INTERVAL_MS) {
            lastSample_ = now;
            if (HostedSession *hs = hs_.load()) {
                sampleTraffic(hs);
            }
        }
        cb_.frame_end(cb_.user);
    }

    void onCursor(const uint32_t *pixels, int width, int height, int negHotX, int negHotY) {
        // The two ints are the negated hotspot: the core's RFB parser
        // rewrites a cursor rectangle to Rect(-hot, size - hot) on arrival
        // and this callback forwards that rectangle's origin.
        if (!pixels || width <= 0 || height <= 0) {
            cb_.cursor(cb_.user, nullptr, 0, 0, 0, 0);
            return;
        }
        cb_.cursor(cb_.user, pixels, width, height, -negHotX, -negHotY);
    }

