    void onSessionClosed() {
        LOGI("sessionClosed");
        // Already closed, so it must not be closed again, either here or by
        // a close still queued.
        coreClosed_ = true;
        reap(false);
        // A requested close reports no reason, whatever the core showed on
        // the way out: an error caused by the disconnect's own close, or one
        // from earlier in the session, is not the reason.
        closed(asked_.load() ? "" : lastError_);
    }

    void onPromptPasswd(int64_t cookie, const std::string &serverName, const char *userName,
                        bool wantsPassword, const std::string &catchphrase,
                        const std::string &signature, const std::string &instructions) {
        (void) catchphrase;
        (void) signature;
        LOGI("password prompt for \"%s\"%s%s%s%s", serverName.c_str(),
             userName ? " (user \"" : "", userName ? userName : "", userName ? "\")" : "",
             wantsPassword ? "" : ", no password wanted");
        if (!instructions.empty()) {
            LOGI("  %s", instructions.c_str());
        }
        if (passwdCookie_ != 0) {
            // The core is not known to ask two at once; the older one is
            // declined rather than lost.
            CoreThread::instance().core()->passwdResult(passwdCookie_, false, nullptr, nullptr);
            promptAnswered();
        }
        passwdCookie_ = cookie;
        proposedUser_ = userName ? userName : "";
        promptShown();
        cb_.credentials_needed(cb_.user, userName != nullptr);
    }

    void onPromptSecurity(int64_t cookie, int identityState, int encryptionState,
                          const std::string &signature, const std::string &catchphrase,
                          const std::string &name, const std::string &matchingName) {
        // The identity is the first argument and the encryption the second,
        // the opposite of what the names in a decompiled signature suggest
        // (see SecurityDlgBindings). The numbers are `vento/backend.h`'s.
        LOGI("promptSecurity id=%d enc=%d name=%s", identityState, encryptionState,
             name.c_str());
        const int identity = identityState >= VENTO_IDENTITY_OK && identityState <= VENTO_IDENTITY_ARD
                                     ? identityState
                                     : VENTO_IDENTITY_MISSING;
        const int encryption = encryptionState >= VENTO_ENCRYPTED
                                               && encryptionState <= VENTO_UNENCRYPTED_QUIET
                                       ? encryptionState
                                       : VENTO_UNENCRYPTED_WARN;
        asks_.emplace_back(Ask::Security, cookie);
        promptShown();
        cb_.security_needed(cb_.user, identity, encryption, signature.c_str(),
                            catchphrase.c_str(), matchingName.c_str());
    }

    void onMsgBox(int64_t cookie, const std::string &message, int flags, const char *custom) {
        const bool question = (flags & MB_OKCANCEL) != 0 || (flags & MB_YESNO) != 0;
        // The icon bits are a small enum in the high nibble, not independent
        // flags: MB_ICONWARNING is 48, which is MB_ICONERROR | MB_ICONQUESTION.
        int severity;
        switch (flags & MB_ICON_MASK) {
            case MB_ICONERROR: severity = VENTO_SEVERITY_ERROR; break;
            case MB_ICONQUESTION: severity = VENTO_SEVERITY_QUESTION; break;
            case MB_ICONWARNING: severity = VENTO_SEVERITY_WARNING; break;
            default: severity = VENTO_SEVERITY_INFORMATION; break;
        }
        LOGI("message (flags %d): %s", flags, message.c_str());
        // The reason `closed` reports, if this is the cause: a refused port,
        // a wrong password and a server that went away all arrive as one of
        // these, followed by a `sessionClosed` with no reason.
        if (severity == VENTO_SEVERITY_ERROR && !question) {
            lastError_ = message;
        }
        asks_.emplace_back(Ask::MsgBox, cookie);
        promptShown();
        cb_.message(cb_.user, message.c_str(), severity, question,
                    (flags & MB_CUSTOM) != 0 && custom ? custom : "");
    }

