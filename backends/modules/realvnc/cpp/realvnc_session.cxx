/* SHA-256 (FIPS 180-4), implemented here rather than taken from a library
   because this file is the neutral layer and has no library under it. Its
   only job is to check whether a file is the pinned one, before anything in
   it runs. */
class Sha256 {
public:
    Sha256() {
        static const uint32_t init[8] = {0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
                                         0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19};
        memcpy(h_, init, sizeof h_);
    }

    void update(const uint8_t *data, size_t len) {
        total_ += len;
        while (len > 0) {
            const size_t take = std::min(len, sizeof block_ - fill_);
            memcpy(block_ + fill_, data, take);
            fill_ += take;
            data += take;
            len -= take;
            if (fill_ == sizeof block_) {
                compress();
                fill_ = 0;
            }
        }
    }

    std::string hex() {
        const uint64_t bits = total_ * 8;
        const uint8_t one = 0x80;
        update(&one, 1);
        const uint8_t zero = 0;
        while (fill_ != 56) {
            update(&zero, 1);
        }
        uint8_t length[8];
        for (int i = 0; i < 8; i++) {
            length[i] = (uint8_t) (bits >> (56 - 8 * i));
        }
        update(length, 8);
        std::string out;
        static const char digits[] = "0123456789abcdef";
        for (uint32_t word : h_) {
            for (int i = 28; i >= 0; i -= 4) {
                out += digits[(word >> i) & 0xf];
            }
        }
        return out;
    }

private:
    static uint32_t rotr(uint32_t x, int n) { return (x >> n) | (x << (32 - n)); }

    void compress() {
        static const uint32_t k[64] = {
                0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1,
                0x923f82a4, 0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3,
                0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786,
                0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
                0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147,
                0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13,
                0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
                0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
                0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a,
                0x5b9cca4f, 0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208,
                0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2};
        uint32_t w[64];
        for (int i = 0; i < 16; i++) {
            w[i] = (uint32_t) block_[4 * i] << 24 | (uint32_t) block_[4 * i + 1] << 16
                   | (uint32_t) block_[4 * i + 2] << 8 | block_[4 * i + 3];
        }
        for (int i = 16; i < 64; i++) {
            const uint32_t s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
            const uint32_t s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16] + s0 + w[i - 7] + s1;
        }
        uint32_t a = h_[0], b = h_[1], c = h_[2], d = h_[3], e = h_[4], f = h_[5], g = h_[6],
                 h = h_[7];
        for (int i = 0; i < 64; i++) {
            const uint32_t s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
            const uint32_t ch = (e & f) ^ (~e & g);
            const uint32_t t1 = h + s1 + ch + k[i] + w[i];
            const uint32_t s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
            const uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
            const uint32_t t2 = s0 + maj;
            h = g;
            g = f;
            f = e;
            e = d + t1;
            d = c;
            c = b;
            b = a;
            a = t1 + t2;
        }
        h_[0] += a;
        h_[1] += b;
        h_[2] += c;
        h_[3] += d;
        h_[4] += e;
        h_[5] += f;
        h_[6] += g;
        h_[7] += h;
    }

    uint32_t h_[8];
    uint8_t block_[64];
    size_t fill_ = 0;
    uint64_t total_ = 0;
};

/* The file's SHA-256 as `sha256sum` prints it, or empty where it could not
   be read. */
std::string sha256Of(const std::string &path) {
    const int fd = open(path.c_str(), O_RDONLY | O_CLOEXEC);
    if (fd < 0) {
        return "";
    }
    Sha256 sha;
    uint8_t buf[65536];
    for (;;) {
        const ssize_t n = read(fd, buf, sizeof buf);
        if (n < 0) {
            close(fd);
            return "";
        }
        if (n == 0) {
            break;
        }
        sha.update(buf, (size_t) n);
    }
    close(fd);
    return sha.hex();
}

/* Checks both libraries against their pins; logs which and returns false
   where either is missing or is a different build. */
bool verifyLibraries(const std::string &dir) {
    const struct {
        const char *name;
        const char *pin;
    } wanted[] = {{"libc++_shared.so", PIN_CXX}, {"libvncviewer.so", PIN_VNCVIEWER}};
    for (const auto &w : wanted) {
        const std::string path = dir + "/" + w.name;
        const std::string have = sha256Of(path);
        if (have.empty()) {
            LOGW("%s: cannot be read", path.c_str());
            return false;
        }
        if (have != w.pin) {
            LOGW("%s: SHA-256 %s is not the pinned build %s's (%s)", path.c_str(), have.c_str(),
                 VENTO_REALVNC_VERSION, w.pin);
            return false;
        }
    }
    return true;
}

// ---- the core thread ----------------------------------------------------------

/* As `RealVncCore`: the core thread, its queue, and the core it brought up.
   A task posted from the thread itself is still queued (rule 5 above); only
   `runBlocking` runs inline there, because waiting on the current thread
   would deadlock. */
class CoreThread {
public:
    static CoreThread &instance() {
        static CoreThread *the = new CoreThread; // never torn down, as rule 1 says
        return *the;
    }

    /* Idempotent. Brings the core up on the thread, blocking until done, and
       sets `*why` on failure. */
    bool start(const std::string &libraryDir, const Bootstrap &bootstrap, std::string *why) {
        const std::lock_guard<std::mutex> guard(startLock_);
        if (core_) {
            return true;
        }
        if (failed_) {
            *why = failure_;
            return false;
        }
        std::mutex m;
        std::condition_variable cv;
        bool done = false;
        thread_ = std::thread([&] {
            std::string reason;
            HostedCore *core = openHostedCore(libraryDir, bootstrap, &reason);
            {
                const std::lock_guard<std::mutex> g(m);
                if (core) {
                    core_ = core;
                } else {
                    failed_ = true;
                    failure_ = reason;
                }
                done = true;
            }
            cv.notify_all();
            if (core) {
                run();
            }
        });
        {
            std::unique_lock<std::mutex> g(m);
            cv.wait(g, [&] { return done; });
        }
        if (!core_) {
            thread_.join();
            *why = failure_;
            return false;
        }
        thread_.detach();
        return true;
    }

    HostedCore *core() const { return core_; }

    bool isCurrent() const { return std::this_thread::get_id() == threadId_; }

    using Task = std::function<void()>;

    void post(Task task) {
        {
            const std::lock_guard<std::mutex> guard(lock_);
            queue_.push_back(std::move(task));
        }
        core_->wake();
    }

    /* Posts a delayed task; returns an id for `cancel`. */
    uint64_t postDelayed(Task task, int delayMs) {
        uint64_t id;
        {
            const std::lock_guard<std::mutex> guard(lock_);
            id = ++lastId_;
            delayed_.emplace(std::chrono::steady_clock::now() + std::chrono::milliseconds(delayMs),
                             Delayed{id, std::move(task)});
        }
        core_->wake();
        return id;
    }

    void cancel(uint64_t id) {
        const std::lock_guard<std::mutex> guard(lock_);
        for (auto it = delayed_.begin(); it != delayed_.end(); ++it) {
            if (it->second.id == id) {
                delayed_.erase(it);
                return;
            }
        }
    }

    /* Runs `task` on the thread and waits for it; inline when already there. */
    void runBlocking(const Task &task) {
        if (isCurrent()) {
            task();
            return;
        }
        std::mutex m;
        std::condition_variable cv;
        bool done = false;
        post([&] {
            task();
            {
                const std::lock_guard<std::mutex> g(m);
                done = true;
            }
            cv.notify_all();
        });
        std::unique_lock<std::mutex> g(m);
        cv.wait(g, [&] { return done; });
    }

private:
    struct Delayed {
        uint64_t id;
        Task task;
    };

    void run() {
        threadId_ = std::this_thread::get_id();
        for (;;) {
            // Runs everything due, then polls until the next delayed task.
            std::deque<Task> ready;
            int timeout = -1;
            {
                const std::lock_guard<std::mutex> guard(lock_);
                ready.swap(queue_);
                const auto now = std::chrono::steady_clock::now();
                while (!delayed_.empty() && delayed_.begin()->first <= now) {
                    ready.push_back(std::move(delayed_.begin()->second.task));
                    delayed_.erase(delayed_.begin());
                }
                if (!delayed_.empty()) {
                    const auto wait = delayed_.begin()->first - now;
                    timeout = (int) std::max<int64_t>(
                            1, std::chrono::duration_cast<std::chrono::milliseconds>(wait).count());
                }
            }
            for (Task &task : ready) {
                task();
            }
            core_->pollOnce(timeout);
        }
    }

    std::mutex startLock_;
    std::thread thread_;
    std::atomic<std::thread::id> threadId_;
    HostedCore *core_ = nullptr;
    bool failed_ = false;
    std::string failure_;

    std::mutex lock_;
    std::deque<Task> queue_;
    std::multimap<std::chrono::steady_clock::time_point, Delayed> delayed_;
    uint64_t lastId_ = 0;
};

