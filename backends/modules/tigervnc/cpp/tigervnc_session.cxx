// A server sends audio only while something is playing (QEMU from the moment
// the guest starts its sound card's stream to the moment it stops it), so a
// session can have any number of these. The stream is opened at the first and
// written as samples arrive, which is all a backend does: the queue behind the
// table keeps as much ahead of the device as the server's rhythm needs and
// drops the oldest past 250 ms, so a burst (a pause's backlog, a socket read
// late behind a large update) costs a skip and not a lag that stays.
//
// At the end the stream is not closed at once, since closing drops what is
// still queued, which is the last few tens of milliseconds of whatever the
// guest played. Nor is it kept open for good, since an open stream with
// nothing written to it keeps the device running on silence (a sound server's
// node that never suspends, an AAudio stream on a phone in a pocket) and keeps
// the session reporting that it is playing. So it is closed once its tail has
// been heard and two seconds more have passed without the server beginning
// again, which is a guest between two sounds rather than a guest that has
// gone quiet.
constexpr int AUDIO_GRACE_MS = 2000;

void Conn::handleAudioBegin() {
    audioIdle_.stop();
    if (soundOn_) {
        s->audioOutput()->open();
    }
}

void Conn::handleAudioEnd() {
    if (s->audioOutput()->isOpen()) {
        audioIdle_.start(s->audioOutput()->tail() + AUDIO_GRACE_MS);
    }
}

// Samples that were on their way when the switch was turned off are dropped
// rather than opening a stream again.
void Conn::handleAudioData(const uint8_t *data, size_t length) {
    audioIdle_.stop();
    if (soundOn_) {
        s->audioOutput()->write(data, length);
    }
}

void Conn::audioIdle(core::Timer *) {
    s->audioOutput()->close();
}

void Conn::endAudio() {
    audioIdle_.stop();
    s->audioOutput()->close();
}

// QEMU's disable takes the client's capture off the guest's card, so nothing
// more is sent until an enable puts it back, and no AudioEnd either, so the
// stream is closed here rather than waiting for one. An enable while the
// guest plays sends samples straight away, often with no AudioBegin before
// them, which is why a write opens the stream. Before the server has said it
// has audio, the switch only changes what it will be asked.
void Conn::setSound(bool on) {
    if (on == soundOn_) {
        return;
    }
    soundOn_ = on;
    if (!soundOffered_) {
        return;
    }
    LOGI("audio: asking the server %s", on ? "for its sound" : "to stop sending its sound");
    writer()->writeQEMUAudioEnable(on);
    if (!on) {
        endAudio();
    }
}

// ---- the protocol thread -------------------------------------------------

// A layout asked for (five ints a screen: id, x, y, width, height) as the
// ScreenSet to send, against the server's own: a screen whose id the server
// has is that screen, moved or resized, and keeps its flags, which is what
// makes this a change to the desktop that is there rather than a new one; a
// screen with an id the server has not, or one already used, is new, and gets
// an id neither the server's layout nor this one has, as the FLTK viewer
// gives its new screens. Lowest first rather than its rand(), so that the same
// request makes the same layout.
rfb::ScreenSet requestedLayout(const rfb::ScreenSet &have, const std::vector<int32_t> &flat) {
    const size_t n = flat.size() / 5;
    std::set<uint32_t> taken;
    for (const rfb::Screen &screen : have) {
        taken.insert(screen.id);
    }
    std::set<uint32_t> kept;
    std::vector<const rfb::Screen *> old(n, nullptr);
    for (size_t i = 0; i < n; i++) {
        const uint32_t id = (uint32_t) flat[i * 5];
        for (const rfb::Screen &screen : have) {
            if (screen.id == id && kept.insert(id).second) {
                old[i] = &screen;
                break;
            }
        }
    }
    uint32_t next = 0;
    rfb::ScreenSet layout;
    for (size_t i = 0; i < n; i++) {
        const int32_t *m = &flat[i * 5];
        if (old[i] != nullptr) {
            rfb::Screen screen = *old[i];
            screen.dimensions.setXYWH(m[1], m[2], m[3], m[4]);
            layout.add_screen(screen);
        } else {
            while (taken.count(next) != 0 || kept.count(next) != 0) {
                next++;
            }
            taken.insert(next);
            layout.add_screen(rfb::Screen(next, m[1], m[2], m[3], m[4], 0));
        }
    }
    return layout;
}

void Session::runCmd(Conn *conn, Cmd &cmd) {
    switch (cmd.type) {
        case CMD_POINTER:
            if (!viewOnly_) {
                // Bits 0–8: the backend API's mask is RFB's, and TigerVNC
                // carries the eighth and ninth through the extended pointer
                // message when the server has asked for it.
                conn->sendPointerEvent(core::Point(cmd.a, cmd.b), (uint16_t) (cmd.c & 0x1FF));
            }
            break;
        case CMD_KEY_DOWN:
            if (!viewOnly_) {
                // The key's identity is the backend API's `key_id`, which is
                // exactly what TigerVNC's `systemKeyCode` is for: it keeps the
                // map of held keys itself and releases the keysym recorded at
                // press time. The other RFB clients keep that map in their own
                // code.
                conn->sendKeyPress((int) cmd.id, 0, (uint32_t) cmd.a);
            }
            break;
        case CMD_KEY_UP:
            if (!viewOnly_) {
                conn->sendKeyRelease((int) cmd.id);
            }
            break;
        case CMD_RELEASE_KEYS:
            if (!viewOnly_) {
                conn->releaseAllKeys();
            }
            break;
        case CMD_CLIPBOARD:
            // The extended clipboard is an announcement and a request, not a
            // send: the server asks for the text if it wants it, which is when
            // `pendingClipboard` is read.
            clipboardOut_ = cmd.text;
            if (!viewOnly_) {
                conn->announceClipboard(true);
            }
            break;
        case CMD_PICTURE:
            applyPicture(conn);
            break;
        case CMD_RESIZE: {
            // Guarded rather than attempted: requestScreenLayout throws where
            // the server never offered one, and an exception out of here ends
            // the session.
            if (viewOnly_ || !conn->server.supportsSetDesktopSize
                    || (conn->server.width() == cmd.a && conn->server.height() == cmd.b)) {
                break;
            }
            // One screen covering the desktop, which is the FLTK viewer's
            // windowed case and the only one a phone has. The screen kept is
            // the server's own, so its id and flags go back as they came: a
            // server matches what it is sent against the screens it has.
            rfb::ScreenSet layout = conn->server.screenLayout();
            while (layout.num_screens() > 1) {
                rfb::ScreenSet::iterator second = layout.begin();
                ++second;
                layout.remove_screen(second->id);
            }
            if (layout.num_screens() == 0) {
                layout.add_screen(rfb::Screen());
            }
            layout.begin()->dimensions.tl.x = 0;
            layout.begin()->dimensions.tl.y = 0;
            layout.begin()->dimensions.br.x = cmd.a;
            layout.begin()->dimensions.br.y = cmd.b;
            if (!layout.validate(cmd.a, cmd.b)) {
                LOGW("not asking for %dx%d: the layout it would need is not valid", cmd.a, cmd.b);
                break;
            }
            conn->requestScreenLayout(cmd.a, cmd.b, layout);
            break;
        }
        case CMD_LAYOUT: {
            if (viewOnly_ || !conn->server.supportsSetDesktopSize) {
                break;
            }
            rfb::ScreenSet layout = requestedLayout(conn->server.screenLayout(), cmd.screens);
            if (!layout.validate(cmd.a, cmd.b)) {
                LOGW("not asking for %dx%d in %d screens: that is not a valid layout", cmd.a, cmd.b,
                     layout.num_screens());
                break;
            }
            if (layout == conn->server.screenLayout() && conn->server.width() == cmd.a
                    && conn->server.height() == cmd.b) {
                break;
            }
            conn->requestScreenLayout(cmd.a, cmd.b, layout);
            break;
        }
        case CMD_SOUND:
            conn->setSound(cmd.a != 0);
            break;
    }
}

// `host::port` is the one unbracketed address with two colons in it that is not
// an IPv6 literal written without brackets.
static bool bareLiteral(const std::string &address) {
    const size_t first = address.find(':');
    const size_t last = address.rfind(':');
    if (first == std::string::npos || first == last) {
        return false;
    }
    return !(last == first + 1 && address.find(':', last + 1) == std::string::npos);
}

// An address is `host`, `host:port`, `[literal]` or `[literal]:port`. A bare
// IPv6 literal is refused in words rather than guessed at, because `:1` is a
// display number here and `::1:1` cannot be an address and a display at once,
// and a guess can produce `::`, which is the wildcard address. The split itself
// is upstream's: it has the display rule, the `host::port` escape from it, and
// unit tests, none of which is worth writing again beside it.
static bool splitAddress(const std::string &address, std::string *host, int *port,
                         std::string *why) {
    const size_t from = address.find_first_not_of(" \t");
    const size_t to = address.find_last_not_of(" \t");
    const std::string trimmed =
            from == std::string::npos ? "" : address.substr(from, to - from + 1);
    if (trimmed.empty() || trimmed[0] == ':') {
        *why = "No host in address";
        return false;
    }
    if (trimmed[0] != '[' && bareLiteral(trimmed)) {
        *why = "IPv6 addresses must be bracketed, like [::1]:5900, not " + trimmed;
        return false;
    }
    try {
        network::getHostAndPort(trimmed.c_str(), host, port, 5900);
    } catch (const std::exception &e) {
        *why = std::string("Not an address: ") + e.what();
        return false;
    }
    return true;
}

std::unique_ptr<network::Socket> Session::openSocket(std::string *why) {
    std::string host;
    int port = 5900;
    if (!splitAddress(address_, &host, &port, why)) {
        return nullptr;
    }
    serverHost_ = host;
    serverPort_ = port;

    if (!net_.connect) {
        try {
            return std::make_unique<network::TcpSocket>(host.c_str(), port);
        } catch (const std::exception &e) {
            *why = std::string("Could not connect: ") + e.what();
            return nullptr;
        }
    }

    vento_net_peer peer = {};
    char reason[256] = "";
    const int fd = net_.connect(net_.user, host.c_str(), port, connectTimeoutMs_, nullptr, &peer, reason,
                                sizeof(reason));
    if (fd < 0) {
        // An empty reason is what the caller reads as a requested disconnect.
        *why = fd == VENTO_NET_ECANCELLED ? ""
                : fd == VENTO_NET_ERESOLVE ? "Cannot find " + host + ": " + reason
                : fd == VENTO_NET_ETIMEDOUT ? "The server did not answer"
                : std::string("Could not connect: ") + reason;
        return nullptr;
    }
    connection_ = peer.connection;
    // TcpSocket turns Nagle's algorithm off, which a socketpair's end has no
    // option for: it would log a warning there and do nothing else.
    if (peer.route == VENTO_NET_TUNNEL) {
        return std::make_unique<network::UnixSocket>(fd);
    }
    return std::make_unique<network::TcpSocket>(fd);
}

// Why the session's connection ended, for the message. A reset reads as the
// end of the stream on a relayed connection and as a socket error on a direct
// one, both worded the same here; the route's answer goes to the log. Only a
// tunnel's own failure is worth more words, which are its own.
std::string Session::lostWords() const {
    const std::string lost = "The connection was lost";
    if (!net_.ended || connection_ <= 0) {
        return lost;
    }
    char why[256] = "";
    const int end = net_.ended(net_.user, connection_, nullptr, why, sizeof(why));
    if (end == VENTO_NET_END_TUNNEL) {
        return lost + ": " + why;
    }
    if (why[0]) {
        LOGI("connection end reason from the session's network: %s", why);
    }
    return lost;
}

void Session::run() {
    std::string why;
    std::unique_ptr<network::Socket> sock = openSocket(&why);
    if (!sock) {
        closed(why);
        return;
    }

    {
        const std::lock_guard<std::mutex> guard(fdLock_);
        fd_ = sock->getFd();
    }
    {
        // A disconnect between the connect and the line above found no
        // socket to shut down, so it is shut down here.
        const std::lock_guard<std::mutex> guard(lock_);
        if (quit_) {
            ::shutdown(sock->getFd(), SHUT_RDWR);
        }
    }
    std::unique_ptr<Conn> conn;
    std::string detail;
    try {
        installSecurityTypes();
        conn.reset(new Conn(this));
        conn->setShared(shared_);
        // Nothing is negotiated yet, so this is only the state the connection
        // starts in; the pixel format it decides is asked for in initDone.
        applyPicture(conn.get());
        conn->setServerName(serverHost_.c_str());
        conn->setStreams(&sock->inStream(), &sock->outStream());
        conn->initialiseProtocol();

        // Kept across passes so that a pass costs nothing it does not use:
        // the swap below hands the empty one to the queue.
        std::deque<Cmd> pending;
        // Set when the last read stopped for want of bytes. What is buffered
        // then is the front of a message, so the buffer's having data is no
        // longer a reason to skip the wait: without this the thread would go
        // straight back to processMsg(), which tries the socket and gives up
        // again, as fast as it can, for as long as the rest of a large
        // rectangle takes to arrive.
        bool starved = false;
        // A server set to ask its user (QueryConnect) sends its
        // SecurityResult only once they answer. The wait is named once it has
        // lasted a second: a server that answers at once is never named.
        const auto approvalDelay = std::chrono::seconds(1);
        std::chrono::steady_clock::time_point approvalSince;
        bool approving = false;
        bool approvalSaid = false;
        for (;;) {
            bool paused;
            {
                std::unique_lock<std::mutex> guard(lock_);
                if (quit_) {
                    break;
                }
                paused = paused_;
                // Held rather than dropped until the connection is up: every
                // command below writes to the server, and nothing may be
                // written until the handshake finishes, which can take as long
                // as the user takes to answer a question about a certificate.
                if (connected_) {
                    pending.swap(queue_);
                }
            }
            for (Cmd &cmd : pending) {
                runCmd(conn.get(), cmd);
            }
            pending.clear();
            // Paused, nothing is read and so nothing is played: the stream
            // goes, and the device with it, until the server's samples are
            // read again and open another. What the server sent meanwhile
            // arrives at once when reading resumes, and the queue keeps only
            // the newest of it.
            if (paused) {
                conn->endAudio();
            }
            {
                const std::lock_guard<std::mutex> guard(lock_);
                if (quit_) {
                    break;
                }
            }

            sock->outStream().flush();
            setTraffic((int64_t) conn->getInStream()->pos(),
                       (int64_t) conn->getOutStream()->length());

            // poll() does not report a message already in the buffer. The
            // buffer asked is the one the messages are read from, which under
            // TLS is the decrypted one and not the socket's.
            const bool buffered = !paused && !starved && conn->getInStream()->hasData(1);
            if (!buffered) {
                // Output the flush above left behind is sent from the top of
                // the loop once the socket has room, so wait for that too,
                // paused or not.
                const bool unsent = sock->outStream().hasBufferedData();
                struct pollfd fds[2];
                int n = 0;
                fds[n++] = {wake_[0], POLLIN, 0};
                if (!paused || unsent) {
                    fds[n++] = {sock->getFd(),
                                (short) ((paused ? 0 : POLLIN) | (unsent ? POLLOUT : 0)), 0};
                }
                int timeout = core::Timer::checkTimeouts();
                timeout = timeout > 0 ? timeout : -1;
                if (conn->state() == rfb::CConnection::RFBSTATE_SECURITY_RESULT) {
                    const auto now = std::chrono::steady_clock::now();
                    if (!approving) {
                        approving = true;
                        approvalSince = now;
                    }
                    const long long left =
                            std::chrono::duration_cast<std::chrono::milliseconds>(
                                    approvalSince + approvalDelay - now)
                                    .count();
                    if (!approvalSaid && left <= 0) {
                        approvalSaid = true;
                        LOGI("waiting for the server to accept the connection");
                        cb_.status(cb_.user, "Waiting for the server to accept the connection…");
                    } else if (!approvalSaid && (timeout < 0 || left < timeout)) {
                        timeout = (int) left;
                    }
                } else {
                    approving = false;
                }
                const int r = poll(fds, n, timeout);
                if (r < 0 && errno != EINTR) {
                    break;
                }
                if (r > 0 && (fds[0].revents & POLLIN) != 0) {
                    char buf[64];
                    while (read(wake_[0], buf, sizeof(buf)) > 0) {
                        // the doorbell, and nothing in it
                    }
                }
                if (n < 2 || paused || (fds[1].revents & (POLLIN | POLLERR | POLLHUP)) == 0) {
                    continue;
                }
            }

            // processMsg() handles at most one message, so this loops until the
            // socket's buffer is empty or the queue needs draining. Only the
            // first says to wait for the socket before the next try; a queue
            // drained leaves whatever is buffered to be read straight after.
            starved = false;
            for (;;) {
                if (!conn->processMsg()) {
                    starved = true;
                    break;
                }
                core::Timer::checkTimeouts();
                const std::lock_guard<std::mutex> guard(lock_);
                if (quit_ || !queue_.empty()) {
                    break;
                }
            }
        }
    } catch (rdr::end_of_stream &e) {
        detail = lostWords();
    } catch (core::socket_error &e) {
        // A reset or a broken pipe on a connection that was up is the same
        // ending as its stream running out, and is said in the same words as
        // libvnc's; the library's own ("read: Connection reset by peer
        // (104)") goes to the log.
        LOGW("the connection ended: %s", e.what());
        detail = lostWords();
    } catch (rfb::auth_cancelled &e) {
        // The user declined, which needs no message, or a certificate was
        // refused without asking, which does.
        detail = conn ? conn->refusal() : "";
    } catch (rfb::auth_error &e) {
        detail = std::string("Authentication failed: ") + e.what();
    } catch (std::exception &e) {
        detail = e.what();
    }

    bool asked;
    {
        const std::lock_guard<std::mutex> guard(lock_);
        asked = quit_;
    }
    if (conn) {
        try {
            conn->close();
        } catch (std::exception &) {
            // Already broken, and this is the goodbye.
        }
        conn->endAudio();
    }
    // The sound switch goes with the session, and none of its calls arrive
    // after this: the session they post to is about to be deleted.
    audioOutput_.withdraw();

    {
        // The reader may be inside readRegion; the framebuffer goes away with
        // the connection, so the copy it reads must stop existing first.
        const std::unique_lock<std::shared_mutex> guard(fbLock_);
        conn.reset();
        {
            const std::lock_guard<std::mutex> guard(fdLock_);
            fd_ = -1;
            sock.reset();
        }
        shadow_.clear();
        shadowW_ = shadowH_ = 0;
    }

    // A requested ending reports nothing, whatever it was caught as:
    // disconnect shuts the socket down under the read, so the stream's end
    // (or a half-read message's error) is this side's own doing and not a
    // reason.
    closed(asked ? "" : (detail.empty() ? "The connection was lost" : detail));
}

// ---- pixels, from whichever thread is drawing ----------------------------

bool Session::readRegion(int x, int y, int w, int h, void *dst, size_t stride, int dstX,
                         int dstY) {
    if (w <= 0 || h <= 0 || dstX < 0 || dstY < 0) {
        return false;
    }
    const std::shared_lock<std::shared_mutex> guard(fbLock_);
    // Subtracted rather than added: `x + w` near INT_MAX overflows, and what
    // it wraps to passes.
    if (shadow_.empty() || x < 0 || y < 0 || x > shadowW_ || y > shadowH_
            || w > shadowW_ - x || h > shadowH_ - y) {
        return false;
    }
    for (int row = 0; row < h; row++) {
        const uint32_t *src = shadow_.data() + (size_t) (y + row) * (size_t) shadowW_ + x;
        uint8_t *out = (uint8_t *) dst + (size_t) (dstY + row) * stride + (size_t) dstX * 4u;
        memcpy(out, src, (size_t) w * 4u);
    }
    return true;
}

bool Session::readThumbnail(int step, void *dst, size_t stride, int dstW, int dstH) {
    if (step < 1) {
        return false;
    }
    const std::shared_lock<std::shared_mutex> guard(fbLock_);
    if (shadow_.empty()) {
        return false;
    }
    const int tw = (shadowW_ + step - 1) / step;
    const int th = (shadowH_ + step - 1) / step;
    if (tw > dstW || th > dstH) {
        return false;
    }
    for (int row = 0; row < th; row++) {
        const uint32_t *src = shadow_.data() + (size_t) (row * step) * (size_t) shadowW_;
        uint32_t *out = (uint32_t *) ((uint8_t *) dst + (size_t) row * stride);
        for (int col = 0; col < tw; col++) {
            out[col] = src[col * step];
        }
    }
    return true;
}

// Desktop name, protocol, connection, security, the encoding the server last
// used, the line speed, and the two pixel formats: the order the Rust
// adapter's `info` labels them in.
bool Session::info(vento_strings *out) {
    std::string desktop, protocol, security, serverPF, viewerPF;
    {
        const std::lock_guard<std::mutex> guard(infoLock_);
        desktop = infoDesktop_;
        protocol = infoProtocol_;
        security = infoSecurity_;
        serverPF = infoServerPF_;
        viewerPF = infoViewerPF_;
    }
    const int encoding = infoEncoding_;
    // H.264 says whether the last picture came out of the hardware, where
    // the decoder knows: the same suffix as RustDesk's.
    std::string encodingText = encoding < 0 ? "" : rfb::encodingName(encoding);
    if (encoding == rfb::encodingH264 && video_.hardware() >= 0) {
        encodingText += video_.hardware() > 0 ? " (hardware)" : " (software)";
    }
    char speed[32];
    snprintf(speed, sizeof(speed), "%u kbit/s", infoLineSpeed_.load() / 1000);

    // The desktop name is the server's, and their reader guarantees only that
    // it is valid UTF-8, as the backend API requires, so it is passed on as it
    // is. The library printed the rest of these.
    const char *values[] = {
            desktop.c_str(),
            protocol.c_str(),
            "TCP",
            security.c_str(),
            encodingText.c_str(),
            speed,
            serverPF.c_str(),
            viewerPF.c_str(),
    };
    return vento_strings_set(out, values, sizeof(values) / sizeof(values[0]));
}

