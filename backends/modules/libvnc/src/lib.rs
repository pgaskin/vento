//! The libvncclient shim (`vento_libvnc`) as a
//! [`Backend`](api::backend::Backend): its config built from the options, its
//! live options and its info rows. The Linux client uses it directly; on the
//! phone the shared JNI layer wraps it, linked into the library Meson builds
//! from the C.

use api::c::{Behaviour, CSession, start};
use api::backend::{Backend, ConnectionFact, Field, Traffic};
use api::kind::{CONNECT_TIMEOUT_MS, Connect, Kind};
use api::options::Options;
use std::ffi::CString;

/// The `vento/libvnc.h` bindings generated by `build.rs`, plus the shared
/// declarations they use.
mod ffi {
    #![allow(non_camel_case_types, dead_code)]
    pub use api::c::ffi::*;
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}

pub static KIND: Kind = Kind {
    about: &api::catalog::LIBVNC,
    version: || LIBRARY.version(|c| unsafe { api::c::string(api::call!(c, ffi::vento_libvnc_version())) }),
    create: api::create_if_loaded!(LIBRARY, "LibVNC", create),
    forget: None,
};

// Registers this backend on the module's generated natives class. Android
// only: the host opens the C as a separate library.
#[cfg(target_os = "android")]
platform_android::natives!(
    class = c"net/pgaskin/remotedesktop/backend/libvnc/LibVncNatives",
    kind = KIND,
);

static BEHAVIOUR: Behaviour = Behaviour {
    info,
    sent_counted: true,
    set_option,
    rdp_domain: false,
};

/// libvncclient's default encoding list, best first. "auto" sends it
/// unchanged; any other value sends that encoding followed by `copyrect`.
const AUTO_ENCODINGS: &str = "tight zrle ultra copyrect hextile zlib corre rre raw";

fn encodings(value: &str) -> String {
    if value.is_empty() || value == "auto" {
        AUTO_ENCODINGS.to_string()
    } else {
        format!("{value} copyrect")
    }
}

/// A 0–9 option as the library wants it, or −1 for "do not send it".
fn level(value: &str) -> i32 {
    value.parse().unwrap_or(-1)
}

/// The colour option as the shim's level: 0 full, 1 rgb222, 2 rgb111.
fn colour(value: &str) -> i32 {
    match value {
        "rgb222" => 1,
        "rgb111" => 2,
        _ => 0,
    }
}

fn create(c: &Connect) -> Result<std::sync::Arc<dyn Backend>, String> {
    let o = c.options;
    let address = CString::new(c.address).map_err(|_| "address has a NUL")?;
    let user = (!c.user.is_empty()).then(|| CString::new(c.user).unwrap_or_default());
    let password = c.password.and_then(|p| CString::new(p).ok());
    let encoding = CString::new(encodings(o.get("Encoding"))).unwrap_or_default();
    let config = ffi::vento_libvnc_config {
        address: address.as_ptr(),
        user_name: user.as_ref().map_or(std::ptr::null(), |u| u.as_ptr()),
        password: password.as_ref().map_or(std::ptr::null(), |p| p.as_ptr()),
        shared: o.bool("Shared"),
        anonymous_tls: o.bool("AnonymousTLS"),
        encoding: encoding.as_ptr(),
        compress_level: level(o.get("Compression")),
        quality_level: level(o.get("Quality")),
        color_level: colour(o.get("ColorLevel")),
        connect_timeout_ms: CONNECT_TIMEOUT_MS,
    };
    log::info!("connecting to {}", c.address);
    let backend = start(
        c,
        &BEHAVIOUR,
        |callbacks| unsafe { api::call!(LIBRARY.loaded(), ffi::vento_libvnc_create(&config, callbacks)) },
        None,
    )?;
    backend.set_view_only(o.bool("ViewOnly"));
    Ok(backend)
}

/// Encoding, compression and quality are live (`SetEncodings` can be sent at
/// any point); the colour depth is not, since the pixel format cannot change
/// while updates are in flight. Shared is fixed at ClientInit, and the bell
/// option is read when a bell arrives.
fn set_option(session: &CSession, o: &Options, key: &str) {
    if matches!(key, "Encoding" | "Compression" | "Quality") {
        let encoding = CString::new(encodings(o.get("Encoding"))).unwrap_or_default();
        unsafe {
            api::call!(LIBRARY.loaded(), ffi::vento_libvnc_set_encodings(
                session.session,
                encoding.as_ptr(),
                level(o.get("Compression")),
                level(o.get("Quality")),
            ))
        }
    }
}

fn info(s: &[String], traffic: Option<Traffic>) -> Vec<ConnectionFact> {
    if s.len() < 7 {
        return Vec::new();
    }
    let mut facts = vec![
        ConnectionFact::of(Field::DesktopName, "Desktop", &s[0]),
        ConnectionFact::of(Field::Protocol, "Protocol", &s[1]),
        ConnectionFact::of(Field::Connection, "Connection", &s[2]),
        ConnectionFact::of(Field::Security, "Security", &s[3]),
        ConnectionFact::of(Field::Encoding, "Encodings offered", &s[4]),
    ];
    if let Some(traffic) = traffic {
        facts.push(ConnectionFact::data(traffic));
    }
    facts.push(ConnectionFact::diagnostic(Field::ServerPixels, "Server pixels", &s[5]));
    facts.push(ConnectionFact::diagnostic(Field::ViewerPixels, "Viewer pixels", &s[6]));
    facts
}

/// The library containing the C. On the Linux client it is
/// `libvento_libvnc.so`, opened on first use, so a library that fails to load
/// makes this backend unavailable instead of stopping the client from
/// starting. On the phone it is linked into the same library as this crate.
#[cfg(target_os = "linux")]
static LIBRARY: api::c::library::Library<ffi::Library> = api::c::library::Library::new(
    "libvento_libvnc.so",
    "vento/libvnc.h",
    api::c::library::Scope::Local,
    ffi::Library::from_library,
);
#[cfg(not(target_os = "linux"))]
static LIBRARY: api::c::library::Linked = api::c::library::Linked;

/// The file `libvento_libvnc.so` was opened from, opening it first, or its name
/// and why it cannot be opened: for the client's list of its backends.
#[cfg(target_os = "linux")]
pub fn library_path() -> Result<std::path::PathBuf, (&'static str, &'static str)> {
    LIBRARY.path()
}
